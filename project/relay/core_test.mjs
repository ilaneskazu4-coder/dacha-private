// Быстрая проверка логики комнаты без сети.
import { RoomCore } from "./relay_core.js";
const log = [];
const mk = (n) => ({ n, got: [], send(u) { this.got.push(Array.from(u)); }, close() { this.closed = true; } });
const r = new RoomCore();
const h = mk("h"), a = mk("a"), b = mk("b");
r.onOpen("host", h); r.onOpen("join", a); r.onOpen("join", b);
let ok = true;
const t = (n, c) => { console.log(c ? "PASS" : "FAIL", n); if (!c) ok = false; };
t("host assigned 1", h.got[0].join() === "1,0,0,0,1");
t("client ids 2,3", a.got[0][4] === 2 && b.got[0][4] === 3);
t("host got joins", h.got[1][4] === 2 && h.got[2][4] === 3);
r.onMessage(a, Uint8Array.of(4, 0, 0, 0, 0, 1, 9, 9));
t("client->host data", h.got[3].join() === "4,0,0,0,2,1,9,9");
r.onMessage(h, Uint8Array.of(4, 0, 0, 0, 3, 0, 7));
t("host->client targeted", b.got[1].join() === "4,0,0,0,1,0,7" && a.got.length === 1);
r.onMessage(h, Uint8Array.of(4, 0, 0, 0, 0, 1, 5));
t("host broadcast", a.got[1].join() === "4,0,0,0,1,1,5" && b.got[2].join() === "4,0,0,0,1,1,5");
const c = mk("c"), d = mk("d");
r.onOpen("join", c); r.onOpen("join", d);
t("room full", d.got[0].join() === "5,3" && d.closed);
r.onMessage(h, Uint8Array.of(6, 0, 0, 0, 2));
t("kick", a.closed && h.got.at(-1).join() === "3,0,0,0,2");
r.onClose(b);
t("leave notify", h.got.at(-1).join() === "3,0,0,0,3");
const r2 = new RoomCore(); const x = mk("x");
r2.onOpen("join", x);
t("no room error", x.got[0].join() === "5,1" && x.closed);
const y = mk("y"), z = mk("z"); r.onOpen("host", y);
t("code in use", y.got[0].join() === "5,2");
r.onClose(h);
t("host left kicks clients", c.got.at(-1).join() === "5,4" && c.closed);
console.log(ok ? "ALL OK" : "FAILED");
process.exit(ok ? 0 : 1);
